"use strict";
// Repackage the existing AIS favicon, without changing its artwork. Run when it changes.
const fs = require("node:fs"), path = require("node:path");
const sharp = require(process.env.SHARP_MODULE || "sharp");
const root = path.resolve(__dirname, "..");
const manifest = {
  id: "./", name: "АИС Допобразование", short_name: "АИС",
  description: "Слушатели, сотрудники, образовательные программы и документы учебного центра.",
  lang: "ru", start_url: "./", scope: "./", display: "standalone",
  background_color: "#f4f6f2", theme_color: "#0f766e", prefer_related_applications: false,
  icons: [
    { src: "pwa-icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
    { src: "pwa-icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
    { src: "pwa-icon-maskable.png", sizes: "512x512", type: "image/png", purpose: "maskable" }
  ]
};
(async () => {
  const assets = {};
  const add = (name, type, bytes) => {
    fs.writeFileSync(path.join(root, name), bytes);
    assets["/" + name] = { type, base64: bytes.toString("base64") };
  };
  add("manifest.webmanifest", "application/manifest+json; charset=utf-8", Buffer.from(JSON.stringify(manifest, null, 2) + "\n"));
  for (const [name, size, inset] of [
    ["pwa-icon-192.png", 192, 0], ["pwa-icon-512.png", 512, 0],
    ["pwa-icon-maskable.png", 512, 64], ["apple-touch-icon.png", 180, 18]
  ]) {
    const bytes = await sharp(path.join(root, "favicon.ico"))
      .resize(size - 2 * inset, size - 2 * inset)
      .extend({ top: inset, bottom: inset, left: inset, right: inset, background: "#ffffff" })
      .flatten({ background: "#ffffff" }).png().toBuffer();
    add(name, "image/png", bytes);
  }
  // Older signed updaters allow new JS files, but not new PNG/manifest files.
  // Local Node serves these exact bytes from the bundle; Apache serves the built files.
  fs.writeFileSync(path.join(root, "pwa-assets.js"), '"use strict";\n// Generated by scripts/build-pwa-assets.js; public metadata/icons only.\nmodule.exports = Object.freeze(' + JSON.stringify(assets, null, 2) + ');\n');
  console.log("Built AIS manifest, four app icons and backward-compatible local asset bundle.");
})().catch(error => { console.error(error); process.exitCode = 1; });
